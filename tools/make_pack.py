"""Build a kernel pack's manifest.json, regions/ and kernels/ from a fusion loop's output.

    python tools/make_pack.py \\
        --regions <loop>/fusion_regions --kernel-cache <loop>/kernel_cache \\
        --log <loop>/iter9.log --plan lift_fusion_region_g006,lift_fusion_region_g020,... \\
        --out graph_trainer_kernel_packs/<pack>

``--log`` is the log of a training run with the plan and the kernel cache
(substitute_kernels from torchtitan PR #5838 logs one ``substitute_kernels hit: <path>``
line per call). Every kernel it hit goes into the pack with its number of calls.
``--plan`` lists the fusion_region_finder lift passes to replay, in order; leave out
regions that no kernel hit. Run this in the target environment: its torch build, CUDA,
GPU and cutlass-dsl versions are recorded as the pack's target. The pack's
``__init__.py``, ``recipe.py`` and ``README.md`` are written by hand.
"""

import argparse
import collections
import hashlib
import json
import re
import shutil
from pathlib import Path

from graph_trainer_kernel_packs.pack import current_target



def _region_source(text: str) -> str:
    """A fusion_region_finder ``lift_pass.py`` without its pass registration."""
    doc_end = text.index('"""', 3)
    doc = text[:doc_end].split("\n\nEach matcher walks")[0]
    # The capture directory is a local path; name it by its loop directory.
    doc = re.sub(
        r"from /\S+?/([^/\s]+?)(?:/capture)?\. In that capture",
        r"from the \1 capture. In that capture",
        doc,
    )
    body = text[doc_end + 3 :]
    body = body.replace(
        "from torchtitan.experiments.graph_trainer.registry import register_graph_pass\n\n",
        "",
    )
    body = body[: body.index("\n\n\n@register_graph_pass")] + "\n"
    old_import = re.search(r"^from lift_regions import .*$", body, flags=re.M).group(0)
    calls = [line for line in body.splitlines() if "is_op(" in line or "user_of(" in line]
    used = ["is_op", "N"] + [
        name
        for name, pattern in (
            ("D", r"[\[ ]D\("),
            ("S", r"[\[ ]S[\],]"),
            ("user_of", r"\buser_of\("),
            ("V", r"[\[ ]V[\],]"),
        )
        if any(re.search(pattern, c) for c in calls)
    ]
    used = sorted(used, key=str.lower)
    body = body.replace(
        old_import, f"from graph_trainer_kernel_packs.lifting import {', '.join(used)}"
    )
    return (
        f"{doc}\n\nLifted by the pack's graph pass, in the order of ``PLAN`` in "
        f'``__init__.py``.\n"""{body}'
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--regions", type=Path, required=True)
    parser.add_argument("--kernel-cache", type=Path, required=True)
    parser.add_argument("--log", type=Path, required=True)
    parser.add_argument("--plan", required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    calls = collections.Counter(
        "/".join(Path(m).parts[-2:])
        for m in re.findall(r"substitute_kernels hit: (\S+)", args.log.read_text())
    )
    if not calls:
        raise ValueError(f"{args.log} has no substitute_kernels hits")

    kernels_dir = args.out / "kernels"
    regions_dir = args.out / "regions"
    for d in (kernels_dir, regions_dir):
        if d.exists():
            shutil.rmtree(d)
    manifest_kernels = {}
    for key in sorted(calls):
        pattern, kernel = key.split("/")
        src, dst = args.kernel_cache / pattern, kernels_dir / pattern
        dst.mkdir(parents=True, exist_ok=True)
        l2 = kernel.removesuffix(".py")
        for name in ("reference.py", f"specialization_{l2}.json", kernel):
            shutil.copyfile(src / name, dst / name)
        sha256 = hashlib.sha256((src / kernel).read_bytes()).hexdigest()
        manifest_kernels[key] = {"sha256": sha256, "calls": calls[key]}

    modules = []
    regions_dir.mkdir(parents=True)
    for pass_name in args.plan.split(","):
        prefix = pass_name.removeprefix("lift_fusion_region_") + "_"
        (folder,) = [d for d in args.regions.iterdir() if d.name.startswith(prefix)]
        text = (folder / "lift_pass.py").read_text()
        (regions_dir / f"{folder.name}.py").write_text(_region_source(text))
        modules.append(folder.name)
    imports = "".join(f"from . import {m}\n" for m in sorted(modules))
    plan = "".join(f"    {m},\n" for m in modules)
    (regions_dir / "__init__.py").write_text(
        '"""Fusion regions of this pack; PLAN is the lift order. Generated by '
        f'tools/make_pack.py."""\n\n{imports}\nPLAN = [\n{plan}]\n'
    )

    manifest = {"target": current_target(), "kernels": manifest_kernels}
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"{args.out}: {len(manifest_kernels)} kernels, {len(modules)} regions")


if __name__ == "__main__":
    main()
